#!/usr/bin/env python3
"""
gate_level.py - synthesise the RTL down to ONLY the basic static-CMOS cells
                INV, NAND2, NOR2 and D flip-flops (DFF / DFFR / DFFS), write the
                structural (gate-level) Verilog netlists, and count transistors.

Flow (Yosys):
    synth -flatten                       generic logic + flip-flops
    dfflegalize                          only plain DFF, DFF+async reset/set
                                         (enables become feedback multiplexers)
    abc -g NAND,NOR                      map all logic to NAND2 / NOR2 / NOT
    write_verilog -noexpr                one instance per gate

Outputs (gate_level/):
    netlist_<cfg>.v          structural netlist using cells from cmos_cells.v
    cell_counts.csv          per-configuration cell and transistor counts
Run from the project root:  python3 scripts/gate_level.py
"""
import csv, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "gate_level")
ECC = ["rtl/sync_fifo_ecc.v", "rtl/secded_enc.v", "rtl/secded_dec.v"]

# name, top, files, parameters (kept in netlist as dummies so testbenches can bind)
CONFIGS = [
    ("enc_w8",        "secded_enc",    ["rtl/secded_enc.v"], {"DATA_W": 8}),
    ("dec_w8",        "secded_dec",    ["rtl/secded_dec.v"], {"DATA_W": 8}),
    ("enc_w32",       "secded_enc",    ["rtl/secded_enc.v"], {"DATA_W": 32}),
    ("dec_w32",       "secded_dec",    ["rtl/secded_dec.v"], {"DATA_W": 32}),
    ("base_w8_d4",    "fifo_baseline", ["rtl/fifo_baseline.v"], {"DATA_W": 8, "DEPTH": 4}),
    ("fifo_w8_d4",    "sync_fifo_ecc", ECC, {"DATA_W": 8, "DEPTH": 4, "ECC_EN": 1}),
    ("fifo_w32_d16",  "sync_fifo_ecc", ECC, {"DATA_W": 32, "DEPTH": 16, "ECC_EN": 1}),
]

CELL_RENAME = {"$_NOT_": "INV", "$_NAND_": "NAND2", "$_NOR_": "NOR2",
               "$_DFF_P_": "DFF", "$_DFF_PN0_": "DFFR", "$_DFF_PN1_": "DFFS"}
TRANSISTORS = {"INV": 2, "NAND2": 4, "NOR2": 4, "DFF": 36, "DFFR": 36, "DFFS": 36}


def yosys(cmds):
    code = ("from pyosys import libyosys as ys; import sys; "
            "ys.run_pass(sys.argv[1], ys.Design())")
    r = subprocess.run([sys.executable, "-c", code, cmds], capture_output=True, text=True)
    if r.returncode != 0 or "ERROR" in r.stdout:
        print(r.stdout[-3000:], r.stderr[-2000:])
        raise SystemExit("yosys failed")
    return r.stdout


def run(name, top, files, params):
    raw = os.path.join(OUT, "_raw_%s.v" % name)
    s = ["read_verilog -defer " + " ".join(os.path.join(ROOT, f) for f in files)]
    s += ["chparam -set %s %d %s" % (k, v, top) for k, v in params.items()]
    s += ["hierarchy -check -top %s" % top,
          "synth -flatten -top %s" % top,
          "dfflegalize -cell $_DFF_P_ 01 -cell $_DFF_PN0_ 01 -cell $_DFF_PN1_ 01",
          "abc -g NAND,NOR",
          "opt_clean -purge",
          "rename -top %s" % top,
          "stat",
          "write_verilog -noattr -noexpr %s" % raw]
    yosys("; ".join(s))
    txt = open(raw).read()
    os.remove(raw)
    # cell names -> readable library names
    for old, new in CELL_RENAME.items():
        txt = txt.replace("\\" + old + " ", new + " ")
    left = set(re.findall(r"\\\$_[A-Z0-9_]+_ ", txt))
    if left:
        raise SystemExit("unexpected cells in %s: %s" % (name, left))
    # port names of yosys internal cells -> our library
    counts = {c: len(re.findall(r"^\s*%s\s" % c, txt, re.M)) for c in TRANSISTORS}
    # keep the parameters as dummies so the original testbenches can bind
    pdecl = "".join("  parameter %s = %d;\n" % (k, v) for k, v in params.items())
    txt = re.sub(r"(module %s\(.*?\);\n)" % top, lambda m: m.group(1) + pdecl, txt, count=1, flags=re.S)
    hdr = ("// Gate-level netlist of %s (%s) generated by scripts/gate_level.py\n"
           "// Cells: INV, NAND2, NOR2, DFF, DFFR, DFFS (see gate_level/cmos_cells.v)\n"
           "// Cell counts: %s\n"
           % (top, ", ".join("%s=%d" % kv for kv in params.items()),
              ", ".join("%s=%d" % (c, n) for c, n in counts.items() if n)))
    open(os.path.join(OUT, "netlist_%s.v" % name), "w").write(hdr + "`timescale 1ns/1ps\n" + txt)
    total_t = sum(TRANSISTORS[c] * n for c, n in counts.items())
    return counts, total_t


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for name, top, files, params in CONFIGS:
        counts, tt = run(name, top, files, params)
        comb = counts["INV"] + counts["NAND2"] + counts["NOR2"]
        ffs = counts["DFF"] + counts["DFFR"] + counts["DFFS"]
        rows.append([name, top, counts["INV"], counts["NAND2"], counts["NOR2"],
                     counts["DFF"], counts["DFFR"], counts["DFFS"], comb, ffs, tt])
        print("%-14s INV=%5d NAND2=%6d NOR2=%6d DFF=%4d DFFR=%3d DFFS=%2d  transistors=%7d"
              % (name, counts["INV"], counts["NAND2"], counts["NOR2"], counts["DFF"],
                 counts["DFFR"], counts["DFFS"], tt))
    with open(os.path.join(OUT, "cell_counts.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["config", "top", "INV", "NAND2", "NOR2", "DFF", "DFFR", "DFFS",
                    "logic_gates", "flip_flops", "transistors"])
        w.writerows(rows)


if __name__ == "__main__":
    main()
